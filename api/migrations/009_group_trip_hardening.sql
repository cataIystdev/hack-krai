-- Миграция 009: Укрепление модуля групповых поездок.
-- Добавляет индекс для предотвращения дублирования анонимных участников
-- по display_name в одной поездке (case-insensitive).

-- =============================================
-- Индекс уникальности анонимных участников
-- =============================================
-- Предотвращает повторное присоединение анонимного участника
-- с тем же display_name к одной поездке.
-- Применяется только к записям с user_id IS NULL.
CREATE UNIQUE INDEX IF NOT EXISTS idx_trip_members_unique_anon
    ON trip_members (trip_id, LOWER(display_name))
    WHERE user_id IS NULL;
