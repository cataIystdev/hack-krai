-- Миграция 004: создание таблицы swipe_scenes для анкетирования свайп-механикой.
-- Каждая сцена представляет визуальный образ с описанием и предвычисленным
-- vibe-вектором 3072 измерений. Турист свайпает вправо (нравится) или влево (не нравится),
-- и его вектор математически сдвигается к/от вектора сцены.

-- ============================================================================
-- Таблица swipe_scenes
-- ============================================================================
CREATE TABLE IF NOT EXISTS swipe_scenes (
    -- Уникальный идентификатор сцены.
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),

-- Заголовок сцены для отображения в интерфейсе.
title TEXT NOT NULL,

-- Описание сцены (2-3 предложения).
description TEXT NOT NULL,

-- URL изображения сцены в MinIO.
image_url TEXT NOT NULL DEFAULT '',

-- Предвычисленный vibe-вектор сцены (3072 float4).
-- Хранится в PostgreSQL для seed/fallback, основной поиск в Qdrant.
vibe_vector FLOAT4[] NOT NULL DEFAULT '{}',

-- Порядок отображения сцен.
display_order INTEGER NOT NULL DEFAULT 0,

-- Временные метки.
created_at TIMESTAMPTZ NOT NULL DEFAULT NOW() );

-- Индекс для упорядоченного отображения сцен.
CREATE INDEX IF NOT EXISTS idx_swipe_scenes_display_order ON swipe_scenes (display_order);

